"""Construct a minimal runtime and retain auditable OS package ownership records."""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path('/runtime-rootfs')


def package_records(status, owners):
    records = {}
    for record in status.split('\n\n'):
        fields = dict(line.split(': ', 1) for line in record.splitlines()
                      if not line.startswith((' ', '\t')) and ': ' in line)
        if fields.get('Package') in owners:
            if fields.get('Status') != 'install ok installed' or not fields.get('Version'):
                raise ValueError('Incomplete installed package inventory')
            records[fields['Package']] = record
    if owners - records.keys():
        raise ValueError('Missing OS package inventory records')
    return '\n\n'.join(records[name] for name in sorted(records)) + '\n\n'


def owners_for(libraries):
    owners, mapping = set(), {}
    for library in sorted(libraries):
        candidates = {str(library), str(library.resolve())}
        candidates |= {name.removeprefix('/usr') for name in candidates if name.startswith('/usr/')}
        found = set()
        for name in sorted(candidates):
            result = subprocess.run(['dpkg-query', '-S', name], capture_output=True, text=True)
            if result.returncode not in (0, 1):
                raise ValueError('OS package lookup failed')
            if result.returncode == 0:
                for line in result.stdout.splitlines():
                    if not line.startswith('diversion ') and ': ' in line:
                        found.add(line.split(': ', 1)[0].split(':', 1)[0])
        if not found:
            raise ValueError(f'No package owner for retained library: {library}')
        owners |= found
        mapping[str(library)] = sorted(found)
    if not owners:
        raise ValueError('Refusing an empty OS package inventory')
    return owners, mapping


def copy(path):
    target = ROOT / str(path).lstrip('/')
    target.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        link = os.readlink(path)
        if not target.exists() and not target.is_symlink():
            target.symlink_to(link)
        copy(Path(link) if Path(link).is_absolute() else path.parent / link)
    elif not target.exists():
        shutil.copy2(path, target)


def main():
    ROOT.mkdir()
    shutil.copytree('/usr/local', ROOT / 'usr/local', symlinks=True)
    # Service code does not use interactive terminal, GUI or native uuid modules.
    # uuid remains functional via its pure-Python implementation.
    removed = []
    for pattern in ('readline.*.so', '_curses*.so', '_uuid.*.so', '_tkinter.*.so'):
        for path in (ROOT / 'usr/local/lib').rglob(pattern):
            removed.append('/' + path.relative_to(ROOT).as_posix())
            path.unlink()
    for app in ('/app', '/home/uter', '/var/lib/uter'):
        if Path(app).exists():
            shutil.copytree(app, ROOT / app.lstrip('/'), symlinks=True)
            subprocess.run(['chown', '-hR', '10001:10001', str(ROOT / app.lstrip('/'))], check=True)
    private = [Path('/usr/local/lib'), *Path('/usr/local/lib').glob('python*/site-packages/torch/lib')]
    env = {**os.environ, 'LD_LIBRARY_PATH': ':'.join(map(str, private))}
    libraries = set()
    for base in ('usr/local', 'app'):
        for path in (ROOT / base).rglob('*'):
            if not path.is_file() or path.is_symlink():
                continue
            with path.open('rb') as stream:
                if stream.read(4) != b'\x7fELF':
                    continue
            original = Path('/') / path.relative_to(ROOT)
            result = subprocess.run(['ldd', str(original)], capture_output=True, text=True, env=env)
            if 'not found' in result.stdout + result.stderr:
                raise ValueError(f'Missing shared library for {original}: {result.stdout}')
            for match in re.findall(r'(?:=>\s+)?(/[^\s()]+)', result.stdout):
                if not match.startswith(('/usr/local/', '/app/')):
                    libraries.add(Path(match))
    for library in libraries:
        copy(library)
    owners, mapping = owners_for(libraries)
    # CA bundle is generated by this package; /etc/os-release belongs to base-files.
    owners |= {'ca-certificates', 'base-files'}
    status = package_records(Path('/var/lib/dpkg/status').read_text(), owners)
    target = ROOT / 'var/lib/dpkg'
    target.mkdir(parents=True)
    (target / 'status').write_text(status)
    for name in ('/etc/os-release', '/etc/debian_version', '/etc/passwd', '/etc/group',
                 '/etc/nsswitch.conf', '/etc/ld.so.cache', '/etc/ssl/certs/ca-certificates.crt'):
        copy(Path(name))
    for owner in owners:
        license = Path('/usr/share/doc') / owner / 'copyright'
        if license.exists():
            copy(license)
    for directory in ('tmp', 'var/tmp'):
        (ROOT / directory).mkdir(parents=True, exist_ok=True)
        (ROOT / directory).chmod(0o1777)
    inventory = ROOT / 'usr/share/uter'
    inventory.mkdir(parents=True)
    (inventory / 'runtime-inventory.json').write_text(json.dumps(dict(os_packages=sorted(owners),
        library_owners=mapping, removed_optional_modules=sorted(removed),
        library_sha256={str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(libraries)}), indent=2))
    print('Retained OS packages:', ', '.join(sorted(owners)))


if __name__ == '__main__':
    main()
