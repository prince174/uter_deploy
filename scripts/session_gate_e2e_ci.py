def fixture(cmd, env, action):
    if action not in ('seed', 'read', 'clean'):
        raise CheckFailure('FIXTURE_ACTION_INVALID')
    try:
        result = sessions.container_command(cmd, env, 'ACTION='+repr(action)+'\n'+_REDIS, 'REDIS')
        if (set(result) != {'count', 'sha256', 'ttl', 'matches'} or type(result['count']) is not int
                or type(result['ttl']) is not int or type(result['matches']) is not bool
                or not re.fullmatch(r'[0-9a-f]{64}', result['sha256'])):
            raise ValueError
        return result
    except Exception:
        raise CheckFailure('FIXTURE_PROBE_FAILED') from None


def verify_restored_fixture(cmd, env, original):
    restored = fixture(cmd, env, 'read')
    if (restored['count'] != original['count'] or restored['sha256'] != original['sha256']
            or not restored['matches'] or not 0 < restored['ttl'] <= original['ttl']):
        raise CheckFailure('RESTORED_FIXTURE_DATA_CHANGED')


def verify_live_old(home, old, public, backend):
    cfg = uterctl.read(home/'install.json')
    state = uterctl.read(home/'state.json')
    if (state.get('adopted_installer') is not True or state.get('pending') is not None
            or state.get('current') != old or cfg.get('images') != old['images']):
        raise CheckFailure('OLD_STATE_NOT_PRESERVED')
    if uterctl.verify(home/'releases'/old['version'], public) != old:
        raise CheckFailure('OLD_SIGNATURE_NOT_PRESERVED')
    old_inputs = ROOT/'work/input/published-old'
    publication = json.loads((old_inputs/'publication.json').read_text())
    harness.verify_active_images(backend, 'uter-upgrade-ci', home, cfg,
                                 ['kubectl', '--context', 'kind-uter-upgrade-ci'], old['images'], publication)
    forward = runner.forward_ready('kind-uter-upgrade-ci', 'uter-upgrade-ci', 18000) if backend == 'kubernetes' else None
    try:
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), runner.NoRedirect())
        with opener.open('http://127.0.0.1:18000/ready', timeout=30) as response:
            if response.status != 200:
                raise CheckFailure('OLD_SERVICE_NOT_READY')
    finally:
        runner.stop_forward(forward)
    try:
        smoke = json.loads(harness.call([sys.executable, home/'runtime/acceptance.py']))
        if not isinstance(smoke, dict) or smoke.get('chat') != 'pass':
            raise ValueError
    except Exception:
        raise CheckFailure('OLD_AUTHENTICATED_SMOKE_FAILED') from None


def run_checked(argv, *, timeout=1800, env=None, limit=65536):
    """Drain output while retaining only a bounded tail, never emit raw text."""
    try:
        proc = subprocess.Popen([str(item) for item in argv], stdin=subprocess.DEVNULL,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=env,
                                start_new_session=True, bufsize=0)
    except OSError:
        raise CheckFailure('UPDATE_PROCESS_UNAVAILABLE') from None
    output = bytearray(); truncated = False; deadline = time.monotonic()+timeout
    def interrupt():
        try: os.killpg(proc.pid, signal.SIGTERM)
        except ProcessLookupError: pass
        try: proc.wait(timeout=30)
        except subprocess.TimeoutExpired:
            try: os.killpg(proc.pid, signal.SIGKILL)
            except ProcessLookupError: pass
            proc.wait()
    try:
        while True:
            remaining = deadline-time.monotonic()
            if remaining <= 0:
                raise CheckFailure('CHILD_INTERRUPTED_CLEANUP_INCONCLUSIVE')
            ready, _, _ = select.select([proc.stdout], [], [], min(1, remaining))
            if ready:
                chunk = os.read(proc.stdout.fileno(), 8192)
                if not chunk: break
                output.extend(chunk)
                if len(output) > limit:
                    truncated = True
                    del output[:-limit]
        try: status = proc.wait(timeout=max(0.01, deadline-time.monotonic()))
        except subprocess.TimeoutExpired:
            raise CheckFailure('CHILD_INTERRUPTED_CLEANUP_INCONCLUSIVE') from None
        if truncated:
            raise CheckFailure('UPDATE_OUTPUT_TOO_LARGE')
        return status, bytes(output)
    except BaseException:
        if proc.poll() is None: interrupt()
        raise
    finally:
        proc.stdout.close()


def assert_blocked(argv, reason, home, old, new, public, backup_root, key, backend):
    if reason not in EXPECTED:
        raise CheckFailure('REASON_INVALID')
    code, raw = run_checked(argv)
    try:
        result = json.loads(raw)
        if code and isinstance(result, dict) and result.get('result') == 'error':
            safe_codes = {'INPUT_OR_VERIFICATION_FAILED', 'SIGNED_UPDATE_FAILED_INSPECT_STATE',
                          'REQUIRED_ARGUMENT_MISSING', 'PLAN_CHANGED', 'CURRENT_SIGNED_BUNDLE_REQUIRED',
                          'CURRENT_BUNDLE_STATE_MISMATCH', 'INSTALLED_BUNDLE_STATE_MISMATCH',
                          'BACKUP_REQUIRES_INSPECTION', 'BACKUP_KEY_INVALID'}
            if result.get('code') in safe_codes:
                raise CheckFailure('WIZARD_'+result['code'])
        if (code == 0 or not isinstance(result, dict) or result.get('result') != 'blocked'
                or result.get('code') != reason or result.get('old_version') != old['version']
                or result.get('new_version') != new['version'] or result.get('backup_independently_verified') is not True
                or not re.fullmatch(r'[0-9a-f]{32}', result.get('backup_id', ''))):
            raise ValueError
        backup = Path(result['backup'])
        if not backup.is_absolute() or backup.parent.resolve() != backup_root.resolve() or backup.is_symlink():
            raise ValueError
        site = uterctl.site_config(home)
        receipt = backup_store.verify_set(backup, backup_crypto.read_key(key), home=home, site=site, version=old['version'])
        if receipt['id'] != result['backup_id']:
            raise ValueError
    except CheckFailure:
        raise
    except (KeyError, TypeError, ValueError, OSError):
        raise CheckFailure('SIGNED_UPDATE_BLOCK_INVALID') from None
    verify_live_old(home, old, public, backend)
    return result


def old_controller_refuses(old_bundle, new_bundle, home, public):
    old_ctl = Path(old_bundle)/'uterctl.py'
    status, response = run_checked([sys.executable, '-I', '-B', str(old_ctl), 'apply', '--home', str(home),
                                    '--bundle', str(new_bundle), '--key', str(public)], timeout=180)
    # The fixed message proves this exact historical controller rejected the
    # epoch transition, rather than failing incidentally for an unrelated error.
    if status == 0 or b'Data migration required' not in response:
        raise CheckFailure('OLD_CONTROLLER_ACCEPTED_EPOCH_CHANGE')


def clear_own_marker(home, blocked):
    marker = home/'session-migration-block.json'
    try:
        raw = marker.lstat()
        if not marker.is_file() or marker.is_symlink() or raw.st_nlink != 1 or raw.st_uid != os.geteuid() or raw.st_mode & 0o077:
            raise ValueError
        data = json.loads(marker.read_text())
        if (data.get('reason') != blocked['code'] or data.get('backup_id') != blocked['backup_id']
                or data.get('backup_path') != blocked['backup']):
            raise ValueError
        marker.unlink()
    except (OSError, ValueError, TypeError):
        raise CheckFailure('OWN_TEST_MARKER_INVALID') from None


