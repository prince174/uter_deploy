                        'RECONNECT','START_WRITERS','CLIENT_CREATE','CLIENT_READY','CLIENT_EXEC',
                        'CLIENT_MISSING_ENV','CLIENT_CONNECT','CLIENT_AUTH','CLIENT_PING',
                        'RECONNECT_PATCH','RECONNECT_ROLLOUT','RECONNECT_DATA',
