class CheckFailure(Exception):
    """Fixed diagnostic without session or credential contents."""


_REDIS = '''import hashlib,json,redis
from redis_config import load_redis_connection_settings
opts=load_redis_connection_settings().client_kwargs();opts['decode_responses']=False
r=redis.Redis(**opts)
test=b'sess:ci-session-gate-ambiguous'; smoke=b'sess:installation-smoke'
values=[b'ci-gate-ambiguous-one',b'ci-gate-ambiguous-two']
if ACTION=='seed':
 if r.exists(test): raise ValueError('fixture exists')
 r.rpush(test,*values);r.expire(test,3600)
elif ACTION=='clean':
 found=set(r.scan_iter(match=b'sess:*',count=100))
 if not found.issubset({test,smoke}): raise ValueError('unexpected session keys')
 if r.exists(test) and r.lrange(test,0,-1)!=values: raise ValueError('fixture changed')
 if test in found:r.delete(test)
 if smoke in found:r.delete(smoke)
 if next(r.scan_iter(match=b'sess:*',count=100),None) is not None: raise ValueError('sessions remain')
elif ACTION!='read': raise ValueError('bad action')
items=r.lrange(test,0,-1)
print(json.dumps({'count':len(items),'sha256':hashlib.sha256(b'\\x00'.join(items)).hexdigest(),
                  'ttl':r.ttl(test),'matches':items==values}))
'''


def fixture(cmd, env, action):
    if action not in ('seed', 'read', 'clean'):
        raise CheckFailure('FIXTURE_ACTION_INVALID')
    try:
        result = sessions.container_command(cmd, env, 'ACTION='+repr(action)+'\n'+_REDIS, 'REDIS')
        if (set(result) != {'count', 'sha256', 'ttl', 'matches'} or type(result['count']) is not int
                or type(result['ttl']) is not int or type(result['matches']) is not bool
                or not re.fullmatch(r'[0-9a-f]{64}', result['sha256'])):
            raise ValueError
        return result
    except Exception:
        raise CheckFailure('FIXTURE_PROBE_FAILED') from None


def verify_live_old(home, old, public, backend):
    cfg = uterctl.read(home/'install.json')
    state = uterctl.read(home/'state.json')
    if (state.get('adopted_installer') is not True or state.get('pending') is not None
            or state.get('current') != old or cfg.get('images') != old['images']):
        raise CheckFailure('OLD_STATE_NOT_PRESERVED')
    if uterctl.verify(home/'releases'/old['version'], public) != old:
        raise CheckFailure('OLD_SIGNATURE_NOT_PRESERVED')
    old_inputs = ROOT/'work/input/published-old'
    publication = json.loads((old_inputs/'publication.json').read_text())
    harness.verify_active_images(backend, 'uter-upgrade-ci', home, cfg,
                                 ['kubectl', '--context', 'kind-uter-upgrade-ci'], old['images'], publication)
    forward = runner.forward_ready('kind-uter-upgrade-ci', 'uter-upgrade-ci', 18000) if backend == 'kubernetes' else None
    try:
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), runner.NoRedirect())
        with opener.open('http://127.0.0.1:18000/ready', timeout=30) as response:
            if response.status != 200:
                raise CheckFailure('OLD_SERVICE_NOT_READY')
    finally:
        runner.stop_forward(forward)
    try:
        smoke = json.loads(harness.call([sys.executable, home/'runtime/acceptance.py']))
        if not isinstance(smoke, dict) or smoke.get('chat') != 'pass':
            raise ValueError
    except Exception:
        raise CheckFailure('OLD_AUTHENTICATED_SMOKE_FAILED') from None


def run_checked(argv, *, timeout=1800, env=None, limit=65536):
    """Drain output while retaining only a bounded tail, never emit raw text."""
    try:
        proc = subprocess.Popen([str(item) for item in argv], stdin=subprocess.DEVNULL,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=env,
                                start_new_session=True, bufsize=0)
    except OSError:
        raise CheckFailure('UPDATE_PROCESS_UNAVAILABLE') from None
    output = bytearray(); truncated = False; deadline = time.monotonic()+timeout
    def interrupt():
        try: os.killpg(proc.pid, signal.SIGTERM)
        except ProcessLookupError: pass
        try: proc.wait(timeout=30)
        except subprocess.TimeoutExpired:
            try: os.killpg(proc.pid, signal.SIGKILL)
            except ProcessLookupError: pass
            proc.wait()
    try:
        while True:
            remaining = deadline-time.monotonic()
            if remaining <= 0:
                raise CheckFailure('CHILD_INTERRUPTED_CLEANUP_INCONCLUSIVE')
            ready, _, _ = select.select([proc.stdout], [], [], min(1, remaining))
            if ready:
                chunk = os.read(proc.stdout.fileno(), 8192)
                if not chunk: break
                output.extend(chunk)
                if len(output) > limit:
                    truncated = True
                    del output[:-limit]
        try: status = proc.wait(timeout=max(0.01, deadline-time.monotonic()))
        except subprocess.TimeoutExpired:
            raise CheckFailure('CHILD_INTERRUPTED_CLEANUP_INCONCLUSIVE') from None
        if truncated:
            raise CheckFailure('UPDATE_OUTPUT_TOO_LARGE')
        return status, bytes(output)
    except BaseException:
        if proc.poll() is None: interrupt()
        raise
    finally:
        proc.stdout.close()


def assert_blocked(argv, reason, home, old, new, public, backup_root, key, backend):
    if reason not in EXPECTED:
        raise CheckFailure('REASON_INVALID')
    code, raw = run_checked(argv)
    try:
        result = json.loads(raw)
        if code and isinstance(result, dict) and result.get('result') == 'error':
            safe_codes = {'INPUT_OR_VERIFICATION_FAILED', 'SIGNED_UPDATE_FAILED_INSPECT_STATE',
                          'REQUIRED_ARGUMENT_MISSING', 'PLAN_CHANGED', 'CURRENT_SIGNED_BUNDLE_REQUIRED',
                          'CURRENT_BUNDLE_STATE_MISMATCH', 'INSTALLED_BUNDLE_STATE_MISMATCH',
                          'BACKUP_REQUIRES_INSPECTION', 'BACKUP_KEY_INVALID'}
            if result.get('code') in safe_codes:
                raise CheckFailure('WIZARD_'+result['code'])
        if (code == 0 or not isinstance(result, dict) or result.get('result') != 'blocked'
                or result.get('code') != reason or result.get('old_version') != old['version']
                or result.get('new_version') != new['version'] or result.get('backup_independently_verified') is not True
                or not re.fullmatch(r'[0-9a-f]{32}', result.get('backup_id', ''))):
            raise ValueError
        backup = Path(result['backup'])
        if not backup.is_absolute() or backup.parent.resolve() != backup_root.resolve() or backup.is_symlink():
            raise ValueError
        site = uterctl.site_config(home)
        receipt = backup_store.verify_set(backup, backup_crypto.read_key(key), home=home, site=site, version=old['version'])
        if receipt['id'] != result['backup_id']:
            raise ValueError
    except CheckFailure:
        raise
    except (KeyError, TypeError, ValueError, OSError):
        raise CheckFailure('SIGNED_UPDATE_BLOCK_INVALID') from None
    verify_live_old(home, old, public, backend)
    return result


def old_controller_refuses(old_bundle, new_bundle, home, public):
    old_ctl = Path(old_bundle)/'uterctl.py'
    status, response = run_checked([sys.executable, '-I', '-B', str(old_ctl), 'apply', '--home', str(home),
                                    '--bundle', str(new_bundle), '--key', str(public)], timeout=180)
    # The fixed message proves this exact historical controller rejected the
    # epoch transition, rather than failing incidentally for an unrelated error.
    if status == 0 or b'Data migration required' not in response:
        raise CheckFailure('OLD_CONTROLLER_ACCEPTED_EPOCH_CHANGE')


def clear_own_marker(home, blocked):
    marker = home/'session-migration-block.json'
    try:
        raw = marker.lstat()
        if not marker.is_file() or marker.is_symlink() or raw.st_nlink != 1 or raw.st_uid != os.geteuid() or raw.st_mode & 0o077:
            raise ValueError
        data = json.loads(marker.read_text())
        if (data.get('reason') != blocked['code'] or data.get('backup_id') != blocked['backup_id']
                or data.get('backup_path') != blocked['backup']):
            raise ValueError
        marker.unlink()
    except (OSError, ValueError, TypeError):
        raise CheckFailure('OWN_TEST_MARKER_INVALID') from None


class Done(Exception):
    pass


def run_scenario():
    stage_tools.validate_inputs(os.environ, ROOT)
    old_call, old_builder, old_audit = harness.call, harness.published_update_command, harness.audit_and_redis
    target = Path(os.environ['NEW_SIGNED_BUNDLE_PATH'])
    source = Path(os.environ['OLD_SIGNED_BUNDLE_PATH'])
    public = Path(os.environ['PUBLISHER_KEY_PATH'])
    old, new = uterctl.verify(source, public), uterctl.verify(target, public)
    if old['data_epoch'] != 1 or new['data_epoch'] != 2 or not new.get('session_identity_gate'):
        raise CheckFailure('EXPECTED_SIGNED_GATE_MISSING')
    saved = []

    def capture(cmd, env, action):
        result = old_audit(cmd, env, action)
        if action == 'write':
            if saved:
                raise CheckFailure('FIXTURE_CAPTURE_REPEATED')
            saved.append((cmd, env, result))
        return result

    def blocked_builder(python, old_bundle, new_bundle, home, key, backup_root, backup_key):
        if len(saved) != 1 or Path(new_bundle) != target or Path(old_bundle) != source:
            raise CheckFailure('SIGNED_FIXTURE_INVALID')
        cmd, env, before_audit = saved[0]
        baseline = fixture(cmd, env, 'seed')
        if baseline['count'] != 2 or not baseline['matches'] or baseline['ttl'] <= 0:
            raise CheckFailure('FIXTURE_SEED_FAILED')
        argv = common.update_command(sys.executable, source, target, home, public, backup_root, backup_key)
        first = assert_blocked(argv, EXPECTED[0], home, old, new, public, backup_root, backup_key, os.environ['BACKEND'])
        after = fixture(cmd, env, 'read')
        if (after['sha256'] != baseline['sha256'] or after['count'] != baseline['count']
                or not after['matches'] or not 0 < after['ttl'] <= baseline['ttl']):
            raise CheckFailure('FIXTURE_DATA_CHANGED')
        old_controller_refuses(source, target, home, public)
        old_audit(cmd, env, 'check')
        clear_own_marker(home, first)
        empty = fixture(cmd, env, 'clean')
        if empty['count'] != 0:
            raise CheckFailure('FIXTURE_CLEAN_FAILED')
        second = assert_blocked(argv, EXPECTED[1], home, old, new, public, backup_root, backup_key, os.environ['BACKEND'])
        old_audit(cmd, env, 'check')
        if second['backup_id'] == first['backup_id']:
            raise CheckFailure('BACKUP_NOT_NEW')
        saved.append({'ambiguous_session_blocked':'pass', 'fixture_data_and_ttl_preserved':'pass',
                      'empty_database_without_external_fence_blocked':'pass',
                      'old_controller_epoch_change_blocked':'pass',
                      'both_encrypted_backups_independently_verified':'pass',
                      'old_version_and_writers_restored':'pass'})
        raise Done()

    harness.audit_and_redis, harness.published_update_command = capture, blocked_builder
    try:
        try:
            harness.main()
        except Done:
            pass
        if len(saved) != 2 or not isinstance(saved[1], dict):
            raise CheckFailure('BLOCK_TEST_INCOMPLETE')
        result = {'backend': os.environ['BACKEND'], 'old_version': old['version'],
                  'new_version': new['version'], **saved[1]}
        path = ROOT/'work/session-gate-e2e-evidence.json'
        fd = os.open(path, os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW, 0o644)
        os.fchmod(fd, 0o644)
        with os.fdopen(fd, 'w', encoding='utf-8') as stream: json.dump(result, stream, indent=2)
        print('SESSION_GATE_E2E_PASS', flush=True)
    finally:
        harness.audit_and_redis, harness.published_update_command, harness.call = old_audit, old_builder, old_call


def staged_main():
    workspace = Path(os.environ['SOURCE_GIT_WORKSPACE'])
    release.verify_assets(ROOT, os.environ['UTER_CI_OLD_TAG'], os.environ['UTER_CI_NEW_TAG'],
                          os.environ['UTER_CI_OLD_VERSION'], os.environ['UTER_CI_NEW_VERSION'],
                          resolve_tag=lambda _, tag: common.tag_commit(workspace, tag))
    run_scenario()


def main():
    stage_tools.validate_inputs(os.environ, ROOT)
    with stage_tools.stage_workspace(ROOT, os.environ) as stage:
        python = stage_tools.prepare_private_python(stage)
        keep = ('GITHUB_ACTIONS','GITHUB_SHA','RUNNER_ENVIRONMENT','RUNNER_OS','BACKEND',
                'UTER_CI_RELEASE_MODE','UTER_CI_STRICT_RUNNER','UTER_CI_OLD_VERSION','UTER_CI_NEW_VERSION',
                'UTER_CI_OLD_TAG','UTER_CI_NEW_TAG','LANG','HOME')
        env = {name:os.environ[name] for name in keep if name in os.environ}
        env.update({'PATH':'/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin',
                    'GITHUB_WORKSPACE':str(stage), 'SOURCE_GIT_WORKSPACE':str(ROOT),
                    'OLD_SIGNED_BUNDLE_PATH':str(stage/'work/pair/old/bundle'),
                    'NEW_SIGNED_BUNDLE_PATH':str(stage/'work/pair/new/bundle'),
                    'PUBLISHER_KEY_PATH':str(stage/'work/pair/old/publisher-public.pem')})
        try:
            status, output = run_checked([str(python), '-I', '-B', str(stage/'scripts/session_gate_e2e_ci.py'),
                                          '--staged'], env=env, timeout=3300, limit=1024*1024)
            if status:
                allowed = {'EXPECTED_SIGNED_GATE_MISSING','FIXTURE_ACTION_INVALID','FIXTURE_PROBE_FAILED',
                           'FIXTURE_CAPTURE_REPEATED','SIGNED_FIXTURE_INVALID','FIXTURE_SEED_FAILED',
                           'SIGNED_UPDATE_BLOCK_INVALID','OLD_STATE_NOT_PRESERVED','OLD_SIGNATURE_NOT_PRESERVED',
                           'OLD_SERVICE_NOT_READY','OLD_AUTHENTICATED_SMOKE_FAILED','FIXTURE_DATA_CHANGED','OLD_CONTROLLER_ACCEPTED_EPOCH_CHANGE',
                           'OWN_TEST_MARKER_INVALID','FIXTURE_CLEAN_FAILED','BACKUP_NOT_NEW','BLOCK_TEST_INCOMPLETE',
                           'UPDATE_PROCESS_UNAVAILABLE','UPDATE_OUTPUT_TOO_LARGE','CHILD_INTERRUPTED_CLEANUP_INCONCLUSIVE',
                           'WIZARD_INPUT_OR_VERIFICATION_FAILED','WIZARD_SIGNED_UPDATE_FAILED_INSPECT_STATE',
                           'WIZARD_REQUIRED_ARGUMENT_MISSING','WIZARD_PLAN_CHANGED','WIZARD_CURRENT_SIGNED_BUNDLE_REQUIRED',
                           'WIZARD_CURRENT_BUNDLE_STATE_MISMATCH','WIZARD_INSTALLED_BUNDLE_STATE_MISMATCH',
                           'WIZARD_BACKUP_REQUIRES_INSPECTION','WIZARD_BACKUP_KEY_INVALID'}
                found = re.findall(rb'(?m)^Session gate test: ([A-Z_0-9]+)\r?$', output)
                code = found[-1].decode('ascii') if found else ''
                raise CheckFailure(code if code in allowed else 'SESSION_GATE_E2E_FAILED')
            source = stage/'work/session-gate-e2e-evidence.json'
            if source.is_symlink() or not source.is_file() or source.stat().st_size > 65536:
                raise CheckFailure('EVIDENCE_INVALID')
            data = source.read_bytes()
            try:
                report = json.loads(data)
                expected = {'ambiguous_session_blocked', 'fixture_data_and_ttl_preserved',
                            'empty_database_without_external_fence_blocked', 'old_controller_epoch_change_blocked',
                            'both_encrypted_backups_independently_verified', 'old_version_and_writers_restored'}
                if (not isinstance(report, dict) or set(report) != expected | {'backend','old_version','new_version'}
                        or report['backend'] != os.environ['BACKEND']
                        or report['old_version'] != os.environ['UTER_CI_OLD_VERSION']
                        or report['new_version'] != os.environ['UTER_CI_NEW_VERSION']
                        or any(report[name] != 'pass' for name in expected)):
                    raise ValueError
                base = os.open(ROOT, os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW)
                try:
                    work = os.open('work', os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW, dir_fd=base)
                    try:
                        fd = os.open('session-gate-e2e-evidence.json',
                                     os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW, 0o644, dir_fd=work)
                        os.fchmod(fd, 0o644)
                        with os.fdopen(fd, 'wb') as stream: stream.write(data)
                    finally:
                        os.close(work)
                finally:
                    os.close(base)
            except (OSError, ValueError, KeyError, TypeError):
                raise CheckFailure('EVIDENCE_INVALID') from None
            print('SESSION_GATE_E2E_PASS', flush=True)
        finally:
            pass


if __name__ == '__main__':
    try:
        if sys.argv[1:] == ['--staged']: staged_main()
        elif not sys.argv[1:]: main()
        else: raise CheckFailure('ARGUMENT_INVALID')
    except (Exception, KeyboardInterrupt) as exc:
        code = str(exc) if isinstance(exc, CheckFailure) and re.fullmatch('[A-Z_0-9]+', str(exc)) else 'SESSION_GATE_E2E_FAILED'
        print('Session gate test: '+code, file=sys.stderr)
        raise SystemExit(1)
